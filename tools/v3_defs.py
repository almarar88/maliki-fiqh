def group_sections(rows):
    """rows: list of (ch, title, item). Returns {ch:[sections]} keeping order, new section when title changes"""
    out={}
    for ch,title,it in rows:
        secs=out.setdefault(ch,[])
        if not secs or secs[-1]['title']!=title: secs.append({'title':title,'items':[]})
        secs[-1]['items'].append(it)
    for ch in out:
        for s in out[ch]:
            while s['items'] and s['items'][-1]['kind']=='h': s['items'].pop()
        out[ch]=[s for s in out[ch] if s['items']]
    return out
